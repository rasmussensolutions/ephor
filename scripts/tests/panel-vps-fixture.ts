await testBootstrap();
const dir = "/var/lib/ephor";
const origin = "https://panel.ephor.test";
const bytes = new Uint8Array(await readFile("/root/ephor-installer"));
const original = JSON.parse(await readFile("/root/release.json", "utf8"));
const release = await verifyRelease(original);
const artifact = { sha256: await sha256(bytes), size: bytes.length };
release.vps = {
  x64: { ...artifact, name: "ephor-installer-linux-x64" },
  arm64: { ...artifact, name: "ephor-installer-linux-arm64" },
  caddyImage: CADDY_IMAGE,
};
const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const key = Buffer.from(
  publicKey.export({ format: "jwk" }).x ?? "",
  "base64url",
).toString("hex");
function signed(r: PanelRelease): SignedRelease {
  const payload = JSON.stringify(r);
  return {
    payload,
    signature: sign(
      null,
      Buffer.from(`ephor:panel-release:v1\n${payload}`),
      privateKey,
    ).toString("hex"),
  };
}
const verify = (e: SignedRelease) => verifyRelease(e, key);
const envelope = signed(release);
